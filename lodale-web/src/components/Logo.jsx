export function Logo({ className = "", variant }) {
  const { isDark } = useTheme();
  const logoVariant = variant || (isDark ? "white" : "moss");
  const textClass =
    logoVariant === "white"
      ? "text-white"
      : logoVariant === "black"
        ? "text-black"
        : isDark
          ? "text-white"
          : "text-ink-900";

  return (
    <div className={`flex items-center gap-2.5 ${className}`}>
      <LogoMark size={32} variant={logoVariant} />
      <span
        className={`text-[24px] leading-none select-none ${textClass}`}
        style={{ fontFamily: "'Playball', cursive" }}
      >
        Lodale
      </span>
    </div>
  );
}

